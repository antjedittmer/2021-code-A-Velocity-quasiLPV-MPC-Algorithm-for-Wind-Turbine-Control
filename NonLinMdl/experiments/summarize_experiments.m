function S = summarize_experiments()
% summarize_experiments evaluates all experiments in experiments/results/*.mat
% and writes results_summary.md.
%
% The metrics are computed from the stored time series T5 (0.04 s
% resolution) in the evaluation window 15 to 400 s (Simulink plant models)
% or 60 to 600 s (FAST), so all experiments are evaluated the same way.

expDir = fileparts(mfilename('fullpath'));
files = dir(fullfile(expDir, 'results', '*.mat'));
rows = {};
for k = 1:numel(files)
    R = load(fullfile(files(k).folder, files(k).name), 'M', 'params', 'T5');
    M = R.M;
    if strcmp(M.plant, 'FAST')
        tEval = [60 600];
    else
        tEval = [15 400];
    end
    m = metrics(R.T5, tEval);
    rows(end+1, :) = {string(M.name), string(M.plant), string(M.wind), string(M.status), M.simulated_s, ...
        sprintf('%g-%g', tEval), m(1), m(2), m(3), m(4), m(5), m(6), m(7), string(paramStr(R.params))}; %#ok<AGROW>
end
S = cell2table(rows, 'VariableNames', {'Name', 'Plant', 'Wind', 'Status', 'Simulated_s', 'Window_s', ...
    'RotSpeed_mean', 'RotSpeed_std', 'RotSpeed_max', 'GenPwr_mean', 'GenPwr_std', 'TwrFA_std', ...
    'PitchRate_std', 'Params'});
S = sortrows(S, 'Name');

fid = fopen(fullfile(expDir, 'results_summary.md'), 'w');
fprintf(fid, ['# Experiment results\n\nGenerated by summarize_experiments.m from the stored time series ' ...
    '(0.04 s resolution). Evaluation window 15-400 s (Simulink plants) or 60-600 s (FAST); runs that ' ...
    'ended earlier are evaluated up to their end. Rotor speed in rpm, power in kW, tower fore-aft ' ...
    'acceleration in m/s^2, pitch rate (from 0.04 s samples) in deg/s.\n\n']);
fprintf(fid, '| Name | Plant | Wind | Status | Sim. [s] | Window [s] | RotSpd mean | RotSpd std | RotSpd max | Power mean | Power std | Tower FA std | Pitch rate std | Parameters |\n');
fprintf(fid, '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n');
for k = 1:height(S)
    fprintf(fid, '| %s | %s | %s | %s | %.0f | %s | %.3f | %.3f | %.2f | %.0f | %.1f | %.3f | %.2f | %s |\n', ...
        S.Name(k), S.Plant(k), S.Wind(k), S.Status(k), S.Simulated_s(k), S.Window_s{k}, S.RotSpeed_mean(k), ...
        S.RotSpeed_std(k), S.RotSpeed_max(k), S.GenPwr_mean(k), S.GenPwr_std(k), S.TwrFA_std(k), ...
        S.PitchRate_std(k), S.Params(k));
end
fclose(fid);
end

function m = metrics(T, tEval)
% [RotSpeed mean, std, max, GenPwr mean, std, TwrFA std, pitch rate std]
m = nan(1, 7);
if isempty(T) || height(T) < 3
    return;
end
DT5 = 0.04;
t = (0:height(T)-1)' * DT5;
i = t >= tEval(1) & t <= tEval(2);
if nnz(i) < 3
    return;
end
m = [mean(T.RotSpeed(i)), std(T.RotSpeed(i)), max(T.RotSpeed(i)), mean(T.GenPwr(i)), std(T.GenPwr(i)), ...
    std(T.NcIMUTAxs(i)), std(diff(T.BlPitch1(i)) / DT5)];
end

function s = paramStr(p)
fn = fieldnames(p);
parts = cell(1, numel(fn));
for k = 1:numel(fn)
    parts{k} = sprintf('%s=%s', fn{k}, mat2str(p.(fn{k}), 3));
end
s = strjoin(parts, ', ');
end
