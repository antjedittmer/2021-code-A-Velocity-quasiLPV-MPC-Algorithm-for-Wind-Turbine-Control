function S = summarize_experiments()
% summarize_experiments collects the metrics of all experiments in
% experiments/results/*.mat into a table and writes results_summary.md.

expDir = fileparts(mfilename('fullpath'));
files = dir(fullfile(expDir, 'results', '*.mat'));
rows = {};
for k = 1:numel(files)
    R = load(fullfile(files(k).folder, files(k).name), 'M', 'params');
    M = R.M;
    p = R.params;
    rows(end+1, :) = {string(M.name), string(M.plant), string(M.wind), string(M.status), M.simulated_s, ...
        g(M, 'RotSpeed_mean'), g(M, 'RotSpeed_std'), g(M, 'RotSpeed_max'), g(M, 'GenPwr_mean'), g(M, 'GenPwr_std'), ...
        g(M, 'TwrFA_std'), g(M, 'PitchRate_std'), string(paramStr(p))}; %#ok<AGROW>
end
S = cell2table(rows, 'VariableNames', {'Name', 'Plant', 'Wind', 'Status', 'Simulated_s', 'RotSpeed_mean', ...
    'RotSpeed_std', 'RotSpeed_max', 'GenPwr_mean', 'GenPwr_std', 'TwrFA_std', 'PitchRate_std', 'Params'});
S = sortrows(S, 'Name');

fid = fopen(fullfile(expDir, 'results_summary.md'), 'w');
fprintf(fid, '# Experiment results\n\nGenerated by summarize_experiments.m. Metrics for t >= 15 s; rotor speed in rpm, power in kW, tower fore-aft acceleration in m/s^2, pitch rate in deg/s.\n\n');
fprintf(fid, '| Name | Plant | Wind | Status | Sim. [s] | RotSpd mean | RotSpd std | RotSpd max | Power mean | Power std | Tower FA std | Pitch rate std | Parameters |\n');
fprintf(fid, '|---|---|---|---|---|---|---|---|---|---|---|---|---|\n');
for k = 1:height(S)
    fprintf(fid, '| %s | %s | %s | %s | %.0f | %.3f | %.3f | %.2f | %.0f | %.1f | %.3f | %.2f | %s |\n', S.Name(k), S.Plant(k), ...
        S.Wind(k), S.Status(k), S.Simulated_s(k), S.RotSpeed_mean(k), S.RotSpeed_std(k), S.RotSpeed_max(k), ...
        S.GenPwr_mean(k), S.GenPwr_std(k), S.TwrFA_std(k), S.PitchRate_std(k), S.Params(k));
end
fclose(fid);
end

function x = g(M, f)
if isfield(M, f), x = M.(f); else, x = NaN; end
end

function s = paramStr(p)
fn = fieldnames(p);
parts = cell(1, numel(fn));
for k = 1:numel(fn)
    v = p.(fn{k});
    parts{k} = sprintf('%s=%s', fn{k}, mat2str(v, 3));
end
s = strjoin(parts, ', ');
end
